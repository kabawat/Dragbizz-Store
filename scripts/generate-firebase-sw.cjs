/**
 * Generates public/firebase-messaging-sw.js from .env.local / .env (SW cannot read Next env at runtime).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_FILE = path.join(ROOT, "public", "firebase-messaging-sw.js");

const FIREBASE_VERSION = "11.6.0";

function loadEnvFile(filename) {
  const filePath = path.join(ROOT, filename);
  if (!fs.existsSync(filePath)) return {};

  const vars = {};
  const content = fs.readFileSync(filePath, "utf8");

  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }

  return vars;
}

function main() {
  const env = {
    ...loadEnvFile(".env"),
    ...loadEnvFile(".env.local"),
    ...process.env,
  };

  const config = {
    apiKey: env.NEXT_PUBLIC_FIREBASE_API_KEY,
    authDomain: env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
    projectId: env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
    messagingSenderId: env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
    appId: env.NEXT_PUBLIC_FIREBASE_APP_ID,
  };

  const missing = Object.entries(config)
    .filter(([, v]) => !v)
    .map(([k]) => k);

  if (missing.length > 0) {
    console.warn(
      `[generate-firebase-sw] Skipping: missing ${missing.join(", ")} in .env.local`
    );
    return;
  }

  const sw = `/* Auto-generated by scripts/generate-firebase-sw.cjs — do not edit manually */
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_VERSION}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_VERSION}/firebase-messaging-compat.js");

firebase.initializeApp({
  apiKey: "${config.apiKey}",
  authDomain: "${config.authDomain}",
  projectId: "${config.projectId}",
  messagingSenderId: "${config.messagingSenderId}",
  appId: "${config.appId}",
});

const messaging = firebase.messaging();

function buildNotificationData(payload) {
  const data = { ...(payload.data || {}) };
  if (payload.notification?.title && !data.title) {
    data.title = payload.notification.title;
  }
  if (payload.notification?.body && !data.body) {
    data.body = payload.notification.body;
  }
  if (!data.url && payload.fcmOptions?.link) {
    data.url = payload.fcmOptions.link;
  }
  return data;
}

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || "Notification";
  const body = payload.notification?.body || payload.data?.body || "";
  const icon = payload.notification?.icon || payload.data?.icon || "/logo.png";
  const badge = payload.notification?.badge || payload.data?.badge;
  const data = buildNotificationData(payload);

  self.registration.showNotification(title, {
    body,
    icon,
    badge,
    data,
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const data = event.notification.data || {};
  const targetPath = data.url || data.click_action || "/dashboard";
  const targetUrl = targetPath.startsWith("http")
    ? targetPath
    : self.location.origin + (targetPath.startsWith("/") ? targetPath : "/" + targetPath);

  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url.startsWith(self.location.origin) && "focus" in client) {
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(targetUrl);
      }
    })
  );
});
`;

  fs.writeFileSync(OUT_FILE, sw, "utf8");
  console.log(`[generate-firebase-sw] Wrote ${OUT_FILE}`);
}

main();
